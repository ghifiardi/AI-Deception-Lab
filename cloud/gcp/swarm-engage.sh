#!/usr/bin/env bash
# Start or stop the isolated swarm engagement stack (gatra-swarm-lab).
#   sudo bash cloud/gcp/swarm-engage.sh start   # keys are printed ONCE for the operator
#   sudo bash cloud/gcp/swarm-engage.sh status
#   sudo bash cloud/gcp/swarm-engage.sh logs
#   sudo bash cloud/gcp/swarm-engage.sh stop
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.."
ACTION=${1:-start}
# Defense mode for this VM's stack (start only). VM1 baseline / VM2 defended comparisons
# pass it explicitly; the default stays defended.
MODE=${2:-defended}
[[ "$MODE" =~ ^(baseline|hardened|defended)$ ]] || { echo 'mode must be baseline|hardened|defended' >&2; exit 2; }
# Ephemeral per engagement; never committed. chmod 600, loopback-only stack.
secret_file=/tmp/gatra-swarm-keys.env
# Use the Docker socket directly when this user may (docker group); otherwise sudo, as on GCP.
if docker info >/dev/null 2>&1; then DOCKER=(docker); else DOCKER=(sudo docker); fi
# Stack-id prefix: gcp (default, lab.sh VMs) or ssh (operator-managed VMs reached over plain SSH).
STACK_PREFIX=${GATRA_STACK_PREFIX:-gcp}
[[ "$STACK_PREFIX" =~ ^(gcp|ssh)$ ]] || { echo 'GATRA_STACK_PREFIX must be gcp or ssh' >&2; exit 2; }
dc() { "${DOCKER[@]}" compose -p gatra-swarm-lab --env-file "$secret_file" -f lab/swarm.compose.yaml "$@"; }
case "$ACTION" in
  start)
    [[ -f "$secret_file" ]] || {
      umask 077
      python3 - "$secret_file" "$STACK_PREFIX" <<'PY'
import re, secrets, socket, sys
from pathlib import Path
# LAB_STACK_ID is a non-secret label for this engagement stack (VM host + random
# suffix); the gateway attests it, MACed with the control key.
stack = sys.argv[2] + ':' + re.sub(r'[^A-Za-z0-9_.-]', '-', socket.gethostname())[:48] + ':' + secrets.token_hex(4)
Path(sys.argv[1]).write_text('LAB_CONTROL_KEY='+secrets.token_hex(32)+'\nLAB_LEGIT_KEY=LABKEY-'+secrets.token_hex(16).upper()+'\nLAB_STACK_ID='+stack+'\n')
PY
    }
    # Non-secret mode line, rewritten on every start so a restart can change mode.
    sed -i '/^DEFENSE_MODE=/d' "$secret_file"
    echo "DEFENSE_MODE=$MODE" >> "$secret_file"
    dc up -d --force-recreate collector defense canary-adapter opencanary swarm-hub
    # The hub may need a few seconds to bind after Docker reports it as started.
    # Retry from the lab network so first boot doesn't fail on a transient refusal.
    for attempt in {1..30}; do
      if "${DOCKER[@]}" run --rm --network gatra-swarm-lab_lab --cap-drop ALL node:22-alpine@sha256:1314fb30ec37592d5845e5a160d522c0e680972aa534549940b8d73bde88481a \
        wget -q -O- --timeout=5 http://swarm-hub:8092/healthz; then
        break
      fi
      if [[ "$attempt" -eq 30 ]]; then
        echo 'Swarm hub did not become healthy after 60 seconds.' >&2
        exit 1
      fi
      sleep 2
    done
    echo
    echo "Swarm stack up (DEFENSE_MODE=$MODE). Hub reachable on VM loopback 127.0.0.1:18092 (IAP tunnel only)."
    echo 'From your machine, open the tunnel, then run the orchestrator and dashboard against it.'
    echo
    echo '--- keys for this engagement (ephemeral, regenerated by "stop && start") ---'
    cat "$secret_file"
    echo '-----------------------------------------------------------------------'
    echo 'Tunnel:  gcloud compute ssh <NAME> --project=<PROJECT> --zone=<ZONE> --tunnel-through-iap --ssh-flag=-N --ssh-flag="-L 18092:localhost:18092"'
    ;;
  status) dc ps ;;
  logs) dc logs --no-color --tail=100 defense swarm-hub collector canary-adapter ;;
  stop)
    dc down
    rm -f -- "$secret_file"
    echo 'Swarm stack removed (V1 demo and defense validation stacks are untouched).'
    ;;
  *) echo "usage: $0 start [baseline|hardened|defended]|status|logs|stop" >&2; exit 2 ;;
esac
